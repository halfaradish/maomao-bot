from pydantic import BaseModel


class Config(BaseModel):
    """一键退群插件配置"""
    data_filename: str = "mass_kick.json"
    # 操作延迟（秒），避免触发频率限制
    operation_delay: float = 1.0
    # 日志群组ID列表（可选），用于记录操作日志
    log_group_ids: list = []
    
    # 没有参数时的默认消息
    DEFAULT_MSG: str = (
        "[一键退群] 命令使用方法\n"
        "[功能]: 批量将指定用户从所有管理的群组中踢出，以及管理群组列表\n"
        "[权限]: 仅超级管理员可使用\n"
        "[格式]:\n"
        "一键退群 QQ号 - 将指定用户从所有管理的群组中踢出\n"
        "一键退群 ls - 查看当前管理的群组列表\n"
        "一键退群 add 群号1 [群号2 群号3 ...] - 添加单个或多个群组到管理列表\n"
        "一键退群 rm 群号1 [群号2 群号3 ...] - 从管理列表删除单个或多个群组\n"
        "\n[示例]:\n"
        "一键退群 123456 - 踢出用户123456\n"
        "一键退群 ls - 查看群组列表\n"
        "一键退群 add 10001 - 添加群组10001\n"
        "一键退群 add 10001 10002 10003 - 批量添加3个群组\n"
        "一键退群 rm 10001 10002 - 批量删除2个群组\n"

        "\n注意：踢人操作不可逆，请谨慎使用"
    )
    
